#ifndef DS_H
#define DS_H

/* ============================================================
 *  项目 4：栈 和 队列
 *
 *  ★ 核心认知：
 *      栈和队列是【接口】（规定"怎么进怎么出"）
 *      数组和链表是【实现】（规定"数据存在哪里"）
 *
 *      同一个接口可以用不同的实现：
 *        · 栈可以用【数组】实现（本项目用它）
 *        · 栈也可以用【链表】实现
 *        · 队列可以用【链表】实现（本项目用它）
 *        · 队列也可以用【数组】实现（叫"循环队列"）
 * ============================================================ */


/* ============================================================
 *  Part A：栈（Stack）—— 用【动态数组】实现
 *
 *  特点：LIFO（Last In First Out，后进先出）
 *        像一摞盘子，只能从顶上拿
 *
 *        入栈 push →  [10][20][30] ← 栈顶
 *        出栈 pop  →  拿到 30
 * ============================================================ */

typedef struct {
    int *data;
    int  size;        /* 栈里几个元素 */
    int  capacity;    /* 数组能装几个 */
} Stack;

/* A1. 创建空栈（初始容量用 4） */
Stack *stack_create(void);

/* A2. 入栈：把 val 放到栈顶
       ⚠️ 满了要扩容（和项目 3 的 da_push 一模一样） */
void stack_push(Stack *s, int val);

/* A3. 出栈：拿走栈顶元素并返回它
       ⚠️ 空栈返回 -1（不崩溃）
       ⚠️ 别忘了 size-- */
int stack_pop(Stack *s);

/* A4. 看栈顶（但不拿走）
       空栈返回 -1 */
int stack_top(Stack *s);

/* A5. 栈空吗？空返回 1，非空返回 0 */
int stack_empty(Stack *s);

/* A6. 栈里几个元素 */
int stack_size(Stack *s);

/* A7. 释放栈（先 free(data)，再 free 结构体） */
void stack_free(Stack *s);


/* ============================================================
 *  Part B：队列（Queue）—— 用【链表】实现
 *
 *  特点：FIFO（First In First Out，先进先出）
 *        像排队买饭，从队尾进、从队头出
 *
 *        入队 push →  [10][20][30]
 *                      ↑front     ↑rear
 *        出队 pop  →  拿到 10
 * ============================================================ */

typedef struct QNode {
    int data;
    struct QNode *next;
} QNode;

typedef struct {
    QNode *front;      /* 队头（出队的一端） */
    QNode *rear;       /* 队尾（入队的一端） */
    int    size;       /* 队列里几个元素 */
} Queue;

/* B1. 创建空队列：front = rear = NULL, size = 0 */
Queue *queue_create(void);

/* B2. 入队：新节点加到【队尾 rear】
       ⚠️ 分两种情况：空队列 / 非空队列
       ⚠️ 别忘了更新 rear 和 size */
void queue_push(Queue *q, int val);

/* B3. 出队：从【队头 front】拿走并返回
       ⚠️ 空队列返回 -1
       ⚠️ 如果出队后队列变空了，rear 也要置成 NULL！ */
int queue_pop(Queue *q);

/* B4. 看队头（但不拿走）。空队列返回 -1 */
int queue_front(Queue *q);

/* B5. 队列空吗？空返回 1，非空返回 0 */
int queue_empty(Queue *q);

/* B6. 队列里几个元素 */
int queue_size(Queue *q);

/* B7. 释放整个队列（所有节点 + 结构体） */
void queue_free(Queue *q);


/* ============================================================
 *  Part C：应用 —— 括号匹配（用栈解决）
 *
 *  判断字符串里的括号是否配对：
 *      "(a+b)"        -> 1（匹配）
 *      "{[()]}"       -> 1
 *      "([)]"         -> 0（交叉了，不匹配）
 *      "((("          -> 0（右括号不够）
 *      ""             -> 1（没有括号，算匹配）
 *
 *  思路（用栈）：
 *      遇到左括号  ( [ {   → 入栈
 *      遇到右括号  ) ] }   → 看栈顶是不是对应的左括号
 *                            是 → 弹栈；不是或栈空 → 不匹配
 *      扫完之后，栈必须是空的
 * ============================================================ */
int brackets_match(const char *s);

#endif  /* DS_H */
